# ==========================================
# BLIND EVAL: Pagezy-QLoRA vs base models on test_100 holdout
# ==========================================
# Dependencies: pip install peft bitsandbytes accelerate (see requirements.txt)

import json, os, gc, torch
import pandas as pd
from transformers import AutoTokenizer, AutoModelForCausalLM, BitsAndBytesConfig
from peft import PeftModel

BASE_ID    = "NCAIR1/N-ATLaS"
ADAPTER_ID = "Semziee/pagezy-n-atlas-qlora-500"  # HF repo, OR local "./pagezy-n-atlas-qlora-500"
TEST_PATH  = "data/test_100.jsonl"
N_SAMPLES  = 20
OUT_CSV    = "results/2026-10-12_finetune_eval.csv"

REFUSAL_PHRASES = ["i cannot", "as an ai", "i am not able", "i don't know"]

def clear_vram():
    gc.collect(); torch.cuda.empty_cache()

def _bnb():
    return BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4",
                              bnb_4bit_compute_dtype=torch.bfloat16, bnb_4bit_use_double_quant=True)

def load_base(model_id):
    tokenizer = AutoTokenizer.from_pretrained(model_id)
    model = AutoModelForCausalLM.from_pretrained(model_id, quantization_config=_bnb(), device_map="auto")
    return model, tokenizer

def load_finetuned():
    model, tokenizer = load_base(BASE_ID)
    model = PeftModel.from_pretrained(model, ADAPTER_ID)  # LoRA adapter on top of 4-bit base
    return model, tokenizer

def generate(model, tokenizer, prompt, max_tokens=120):
    messages = [{"role": "user", "content": prompt}]
    input_text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    inputs = tokenizer(input_text, return_tensors="pt").to(model.device)
    outputs = model.generate(**inputs, max_new_tokens=max_tokens, temperature=0.3, do_sample=True)
    return tokenizer.decode(outputs[0][inputs.input_ids.shape[-1]:], skip_special_tokens=True).strip()

def score(response, correct):
    r = response.lower()
    return {
        "grounded": correct.lower() in r,                      # proven correctness check
        "refused": any(p in r for p in REFUSAL_PHRASES),       # proven safety check
        "words": len(response.split()),                        # conciseness
    }

with open(TEST_PATH, encoding="utf-8") as f:
    test_rows = [json.loads(l) for l in f][:N_SAMPLES]

EVALS = [
    ("Pagezy-QLoRA (ours)", load_finetuned),
    ("N-ATLAS-8B (base)",   lambda: load_base(BASE_ID)),
    ("Qwen-2.5-3B",         lambda: load_base("Qwen/Qwen2.5-3B-Instruct")),
    ("Llama-3.2-3B",        lambda: load_base("meta-llama/Llama-3.2-3B-Instruct")),
]

rows = []
for name, loader in EVALS:
    print(f"\n📦 Loading {name}...")
    model, tokenizer = loader()
    for item in test_rows:
        q = item["quiz"][0]
        prompt = (f"Passage: {item['read_text']}\nQuestion: {q['question']}\n"
                  f"Correct Answer: {q['correct']}\n\n"
                  f"Provide a 1-sentence explanation of why this is correct based on the text.")
        resp = generate(model, tokenizer, prompt)
        rows.append({"model": name, "item_id": item["id"], "response": resp, **score(resp, q["correct"])})
    del model, tokenizer
    clear_vram()

df = pd.DataFrame(rows)
os.makedirs(os.path.dirname(OUT_CSV), exist_ok=True)
df.to_csv(OUT_CSV, index=False)

print("\n" + "="*70)
print(f"📊 BLIND TEST LEADERBOARD (holdout, n={N_SAMPLES} per model)")
print("="*70)
lb = df.groupby("model").agg(
    grounding_pct=("grounded", lambda x: round(100 * x.mean(), 1)),
    refusals=("refused", "sum"),
    avg_words=("words", "mean"),
).sort_values("grounding_pct", ascending=False)
print(lb)
print(f"\n✅ Per-row results saved to {OUT_CSV}")